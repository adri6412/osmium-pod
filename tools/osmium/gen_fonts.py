#!/usr/bin/env python3
"""Osmium Sound for Rockbox: anti-aliased fonts as C arrays.

The Osmium interface is set in DejaVu Sans (and DejaVu Sans Mono for the
times). This renders the sizes the M3K screen uses into 4-bit alpha glyph
bitmaps, cropped to their ink box, and writes apps/osmium/assets/osm_fonts.c.

    python3 tools/osmium/gen_fonts.py [dejavu-dir]

Needs Pillow with FreeType. The default font directory is the one Debian
and Ubuntu install (fonts-dejavu-core).
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

FONT_DIR = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu"
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT_C = os.path.join(ROOT, "apps", "osmium", "assets", "osm_fonts.c")
OUT_H = os.path.join(ROOT, "apps", "osmium", "assets", "osm_fonts.h")

# id, file, pixel size, letter spacing (1/16 px)
FONTS = [
    ("OSM_FONT_R10", "DejaVuSans.ttf", 10),
    ("OSM_FONT_R11", "DejaVuSans.ttf", 11),
    ("OSM_FONT_R12", "DejaVuSans.ttf", 12),
    ("OSM_FONT_R13", "DejaVuSans.ttf", 13),
    ("OSM_FONT_R15", "DejaVuSans.ttf", 15),
    ("OSM_FONT_B10", "DejaVuSans-Bold.ttf", 10),
    ("OSM_FONT_B12", "DejaVuSans-Bold.ttf", 12),
    ("OSM_FONT_B13", "DejaVuSans-Bold.ttf", 13),
    ("OSM_FONT_B15", "DejaVuSans-Bold.ttf", 15),
    ("OSM_FONT_B18", "DejaVuSans-Bold.ttf", 18),
    ("OSM_FONT_B22", "DejaVuSans-Bold.ttf", 22),
    ("OSM_FONT_B32", "DejaVuSans-Bold.ttf", 32),
    ("OSM_FONT_M10", "DejaVuSansMono.ttf", 10),
    ("OSM_FONT_M11", "DejaVuSansMono.ttf", 11),
]

# Latin-1, Latin Extended-A, and the typography that turns up in tags
CODEPOINTS = (
    list(range(0x20, 0x7F))
    + list(range(0xA0, 0x180))
    + [0x2013, 0x2014, 0x2018, 0x2019, 0x201A, 0x201C, 0x201D, 0x201E,
       0x2020, 0x2022, 0x2026, 0x2032, 0x2033, 0x20AC, 0x2122, 0x2190,
       0x2192, 0x25B6, 0x266A, 0x266B]
)
# the big bold size is only for the clock and the boot screen
DIGITS_ONLY = {"OSM_FONT_B32": [ord(c) for c in "0123456789: %."] }


def render(font_file, size, cps):
    font = ImageFont.truetype(os.path.join(FONT_DIR, font_file), size)
    ascent, descent = font.getmetrics()
    glyphs = []
    for cp in cps:
        ch = chr(cp)
        if font.getmask(ch).getbbox() is None and ch.strip() and cp not in (0xA0,):
            # not in the font: leave it to the fallback
            if cp >= 0x80:
                continue
        adv = font.getlength(ch)
        box = font.getbbox(ch)                  # relative to the origin, top = ascender line
        w = max(1, box[2] - box[0] + 2)
        h = ascent + descent + 2
        img = Image.new("L", (w + 4, h + 4), 0)
        ImageDraw.Draw(img).text((2 - box[0], 2), ch, font=font, fill=255)
        ink = img.getbbox()
        if ink is None:
            glyphs.append((cp, round(adv), 0, 0, 0, 0, b""))
            continue
        crop = img.crop(ink)
        bw, bh = crop.size
        xoff = ink[0] - 2 + box[0]
        yoff = ink[1] - 2                       # from the top of the line
        px = list(crop.tobytes())
        data = bytearray()
        for y in range(bh):
            row = px[y * bw:(y + 1) * bw]
            for x in range(0, bw, 2):
                a = (row[x] + 8) // 17
                b = (row[x + 1] + 8) // 17 if x + 1 < bw else 0
                data.append((a << 4) | b)
        glyphs.append((cp, round(adv), xoff, yoff, bw, bh, bytes(data)))
    return ascent, descent, glyphs


def main():
    out = []
    out.append("/* Generated by tools/osmium/gen_fonts.py from DejaVu fonts — do not edit.\n"
               " * DejaVu fonts: Bitstream Vera license (see the DejaVu distribution). */\n")
    out.append('#include "osm_fonts.h"\n\n')
    hdr = ["/* Generated by tools/osmium/gen_fonts.py — do not edit. */\n",
           "#ifndef OSM_FONTS_H\n#define OSM_FONTS_H\n#include <stdint.h>\n\n",
           "struct osm_glyph {\n    uint16_t cp;      /* code point */\n    uint8_t  adv;     /* advance */\n"
           "    int8_t   xoff;    /* ink box from the pen */\n    uint8_t  yoff;    /* ink box from the top of the line */\n"
           "    uint8_t  w, h;    /* ink box */\n    uint32_t off;     /* into bits: 4-bit alpha, rows padded to bytes */\n};\n\n",
           "struct osm_font {\n    uint8_t height;   /* line height */\n    uint8_t ascent;\n    uint16_t count;\n"
           "    const struct osm_glyph *glyphs;   /* sorted by code point */\n    const uint8_t *bits;\n};\n\n",
           "enum osm_font_id {\n"]
    total = 0
    for fid, ffile, size in FONTS:
        cps = DIGITS_ONLY.get(fid, CODEPOINTS)
        ascent, descent, glyphs = render(ffile, size, cps)
        name = fid.lower()
        bits = bytearray()
        rows = []
        for cp, adv, xoff, yoff, bw, bh, data in glyphs:
            rows.append(f"    {{0x{cp:04x},{adv},{xoff},{yoff},{bw},{bh},{len(bits)}}},")
            bits += data
        total += len(bits) + len(glyphs) * 12
        out.append(f"static const uint8_t {name}_bits[] = {{\n")
        for i in range(0, len(bits), 24):
            out.append("    " + ",".join(f"0x{b:02x}" for b in bits[i:i + 24]) + ",\n")
        out.append("};\n")
        out.append(f"static const struct osm_glyph {name}_glyphs[] = {{\n" + "\n".join(rows) + "\n};\n\n")
        hdr.append(f"    {fid},\n")
    hdr.append("    OSM_FONT_COUNT\n};\n\nextern const struct osm_font osm_fonts[OSM_FONT_COUNT];\n\n#endif\n")
    out.append("const struct osm_font osm_fonts[OSM_FONT_COUNT] = {\n")
    for fid, ffile, size in FONTS:
        font = ImageFont.truetype(os.path.join(FONT_DIR, ffile), size)
        ascent, descent = font.getmetrics()
        name = fid.lower()
        out.append(f"    [{fid}] = {{ {ascent + descent}, {ascent}, "
                   f"sizeof({name}_glyphs)/sizeof({name}_glyphs[0]), {name}_glyphs, {name}_bits }},\n")
    out.append("};\n")
    with open(OUT_C, "w") as f:
        f.write("".join(out))
    with open(OUT_H, "w") as f:
        f.write("".join(hdr))
    print(f"{OUT_C}: {total // 1024} KiB")


if __name__ == "__main__":
    main()
