def raster(svg_path, size):
    png = cairosvg.svg2png(url=svg_path, output_width=size * 4, output_height=size * 4)
    img = Image.open(io.BytesIO(png)).convert("RGBA").getchannel("A")
    # 4x supersampling, then a box filter: crisp strokes at 1.3 px
    return img.resize((size, size), Image.BOX)


def main():
    c = ["/* Generated by tools/osmium/gen_icons.py — do not edit.\n"
         " * Lucide icons (ISC license, https://lucide.dev) as used by Osmium Sound. */\n",
         '#include "osm_icons.h"\n\n']
    h = ["/* Generated by tools/osmium/gen_icons.py — do not edit. */\n",
         "#ifndef OSM_ICONS_H\n#define OSM_ICONS_H\n#include <stdint.h>\n\n",
         "struct osm_icon_bitmap {\n    uint8_t icon;     /* enum osm_icon */\n    uint8_t size;     /* square, pixels */\n"
         "    const uint8_t *bits;  /* 4-bit alpha, rows padded to bytes */\n};\n\nenum osm_icon {\n"]
    table = []
    total = 0
    for name, sizes in ICONS.items():
        ident = "ICON_" + name.upper().replace("-", "_")
        h.append(f"    {ident},\n")
        path = os.path.join(SRC, name + ".svg")
        for size in sizes:
            a = raster(path, size)
            px = a.tobytes()
            data = bytearray()
            for y in range(size):
                row = px[y * size:(y + 1) * size]
                for x in range(0, size, 2):
                    p = (row[x] + 8) // 17
                    q = (row[x + 1] + 8) // 17 if x + 1 < size else 0
                    data.append((p << 4) | q)
            var = f"ic_{name.replace('-', '_')}_{size}"
            c.append(f"static const uint8_t {var}[] = {{" + ",".join(f"0x{b:02x}" for b in data) + "};\n")
            table.append(f"    {{ {ident}, {size}, {var} }},")
            total += len(data)
    h.append("    ICON_COUNT\n};\n\n#define OSM_ICON_BITMAP_COUNT %d\n"
             "extern const struct osm_icon_bitmap osm_icon_bitmaps[OSM_ICON_BITMAP_COUNT];\n\n#endif\n" % len(table))
    c.append("\nconst struct osm_icon_bitmap osm_icon_bitmaps[OSM_ICON_BITMAP_COUNT] = {\n" + "\n".join(table) + "\n};\n")
    open(OUT_C, "w").write("".join(c))
    open(OUT_H, "w").write("".join(h))
    print(f"{OUT_C}: {len(table)} bitmaps, {total // 1024} KiB")


if __name__ == "__main__":
    main()
