#!/usr/bin/env python3
"""Osmium Sound for Rockbox: the picture assets as C arrays.

From an Osmium Sound checkout (native-ui-qt/assets): the LED status plate
(Hi-Res / PCM / DSD, BitPerfect, ReplayGain) and the analogue VU meter
looks, scaled for the 240x320 screen of the FiiO M3K, as RGB565 with an
optional 8-bit alpha plane: apps/osmium/assets/osm_images.[ch].

    python3 tools/osmium/gen_images.py /path/to/osmium-sound
"""
import json
import os
import sys

from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OSM = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "..", "osmium-sound")
ASSETS = os.path.join(OSM, "native-ui-qt", "assets")
OUT_C = os.path.join(ROOT, "apps", "osmium", "assets", "osm_images.c")
OUT_H = os.path.join(ROOT, "apps", "osmium", "assets", "osm_images.h")

LED_W = 228                       # the plate under the cover
VU_W = 240                        # a VU meter look, full screen width
VU_SKINS = ["classic", "amber", "ice-blue", "modulometer", "exposed", "panoramic"]

out_c = ["/* Generated by tools/osmium/gen_images.py from Osmium Sound's artwork — do not edit. */\n",
         '#include "osm_images.h"\n\n']
names = []


def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def emit(name, img, crop=True, opaque=False):
    """img: RGBA. Returns the C initializer of a struct osm_image."""
    x0 = y0 = 0
    if crop:
        box = img.getchannel("A").getbbox()
        if box is None:
            box = (0, 0, 1, 1)
        x0, y0 = box[0], box[1]
        img = img.crop(box)
    w, h = img.size
    px = img.tobytes()
    rgb = []
    alpha = bytearray()
    for i in range(w * h):
        r, g, b, a = px[i * 4:i * 4 + 4]
        if not opaque and a:
            # un-premultiplied colour; keep it as is
            pass
        rgb.append(rgb565(r, g, b))
        alpha.append(a)
    out_c.append(f"static const uint16_t {name}_rgb[] = {{\n")
    for i in range(0, len(rgb), 16):
        out_c.append("    " + ",".join(f"0x{v:04x}" for v in rgb[i:i + 16]) + ",\n")
    out_c.append("};\n")
    a_ref = "0"
    if not opaque:
        out_c.append(f"static const uint8_t {name}_a[] = {{\n")
        for i in range(0, len(alpha), 24):
            out_c.append("    " + ",".join(f"{v}" for v in alpha[i:i + 24]) + ",\n")
        out_c.append("};\n")
        a_ref = f"{name}_a"
    names.append(name)
    return f"{{ {x0}, {y0}, {w}, {h}, {name}_rgb, {a_ref} }}", (len(rgb) * 2 + (0 if opaque else len(alpha)))


def scaled(path, w, h):
    return Image.open(path).convert("RGBA").resize((w, h), Image.LANCZOS)


def main():
    total = 0
    defs = []
    # ── LED plate ────────────────────────────────────────────────────
    lh = round(LED_W * 175 / 897)
    led = {}
    for part in ["base", "hires", "pcm", "dsd", "bitperfect", "replaygain"]:
        img = scaled(os.path.join(ASSETS, "ledbar", f"led-bar-{part}.png"), LED_W, lh)
        init, size = emit(f"led_{part}", img, crop=(part != "base"))
        led[part] = init
        total += size
    defs.append("const struct osm_led_plate osm_led_plate = {\n    %d, %d,\n" % (LED_W, lh) +
                "".join(f"    {led[p]},\n" for p in ["base", "hires", "pcm", "dsd", "bitperfect", "replaygain"]) + "};\n")

    # ── VU meters ────────────────────────────────────────────────────
    skins = []
    for sid in VU_SKINS:
        d = os.path.join(ASSETS, "vu", sid)
        s = json.load(open(os.path.join(d, "skin.json")))
        sw, sh = s["size"]
        k = VU_W / sw
        vh = round(sh * k)
        n = sid.replace("-", "_")
        under, su = emit(f"vu_{n}_under", scaled(os.path.join(d, s["under"]), VU_W, vh), crop=False, opaque=True)
        over, so = emit(f"vu_{n}_over", scaled(os.path.join(d, s["over"]), VU_W, vh))
        total += su + so
        nd = s["needle"]
        if nd.get("image"):
            nw = max(1, round(nd["width"] * k))
            nh = max(1, round(nd["height"] * k))
            needle, sn = emit(f"vu_{n}_needle", scaled(os.path.join(d, nd["image"]), nw, nh), crop=False)
            total += sn
            px, py = nd["pivotX"] * k, nd["pivotY"] * k
            color = "0"
            line = "0, 0, 0"
        else:
            needle = "{ 0, 0, 0, 0, 0, 0 }"
            px = py = 0
            c = nd.get("color", "#111111").lstrip("#")
            color = "0x%04x" % rgb565(int(c[0:2], 16), int(c[2:4], 16), int(c[4:6], 16))
            line = f"{round(max(nd.get('minWidth', 1), nd['width'] * k) * 16)}, {round(nd['height'] * k * 16)}, {round(nd.get('cap', 0) * k * 16)}"
        m = s["meters"]
        a = s["angles"]
        title = s["name"]
        skins.append(
            f"    {{ \"{title['en']}\", \"{title['it']}\", {VU_W}, {vh},\n"
            f"      {under},\n      {over},\n      {needle},\n"
            f"      {round(px * 16)}, {round(py * 16)}, {color}, {line},\n"
            f"      {{ {{ {round(m[0][0] * k * 16)}, {round(m[0][1] * k * 16)} }}, {{ {round(m[1][0] * k * 16)}, {round(m[1][1] * k * 16)} }} }},\n"
            f"      {round(a[0] * 10)}, {round(a[1] * 10)} }},")
    defs.append("const struct osm_vu_skin osm_vu_skins[OSM_VU_SKIN_COUNT] = {\n" + "\n".join(skins) + "\n};\n")

    out_c.append("\n" + "\n".join(defs))
    open(OUT_C, "w").write("".join(out_c))
    open(OUT_H, "w").write(f"""/* Generated by tools/osmium/gen_images.py — do not edit. */
#ifndef OSM_IMAGES_H
#define OSM_IMAGES_H
#include <stdint.h>

/* an RGB565 picture placed at (x, y) of its canvas; alpha NULL = opaque */
struct osm_image {{
    int16_t x, y, w, h;
    const uint16_t *rgb;
    const uint8_t *alpha;
}};

struct osm_led_plate {{
    int16_t w, h;
    struct osm_image base, hires, pcm, dsd, bitperfect, replaygain;
}};
extern const struct osm_led_plate osm_led_plate;

/* An analogue VU meter look, from Osmium's skins. Coordinates in 1/16 px,
 * angles in 1/10 degree (0 = straight up, positive clockwise). */
struct osm_vu_skin {{
    const char *name_en, *name_it;
    int16_t w, h;
    struct osm_image under, over;
    struct osm_image needle;          /* w == 0: a drawn line needle */
    int16_t pivot_x, pivot_y;         /* in the needle picture */
    uint16_t line_color;
    int16_t line_w, line_h, line_cap;
    int16_t meters[2][2];             /* pivot of each needle on the face */
    int16_t angle_min, angle_max;
}};
#define OSM_VU_SKIN_COUNT {len(VU_SKINS)}
extern const struct osm_vu_skin osm_vu_skins[OSM_VU_SKIN_COUNT];

#endif
""")
    print(f"{OUT_C}: {total // 1024} KiB")


if __name__ == "__main__":
    main()
